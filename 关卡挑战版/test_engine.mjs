/* 卡牌对战 · 引擎自测（node，纯逻辑，不需要浏览器、不需要桩 DOM）
 *
 * 引擎与事件层是**纯逻辑**：不碰 DOM、不用全局时钟、不用 Math.random。
 * 所以这份测试能直接把它们装进 node 跑真实的规则 —— 不需要任何替身。
 *
 * 验七件事：
 *   A 装载 + 纯逻辑硬约束（源码里不许出现 document/window/Date.now/Math.random）
 *   B 稳定串与哈希（键序无关、同状态同哈希）
 *   C 变更可重放（新状态 === 应用(原状态, 变更)，逐条命令都成立）
 *   D 事件契约（顺序号递增、id 唯一、类别合法、fx 不改状态、因果有据）
 *   E 席位投影（对手手牌/牌库是隐藏信息）
 *   F 规则：状态检查（死亡/胜负/亡语）、优先权与堆叠（攻击那一拍才结算、响应能插、嘲讽）、
 *          待选择（战吼要选目标，引擎绝不自己猜）
 *   G 标准对局回归基线（命令序列 + 事件摘要 + 末态哈希）—— 规则改动最容易悄悄改坏别处，
 *          有基线才敢动。基线变了但你没打算改规则，就是踩到东西了。
 *
 * 跑： node test_engine.mjs
 *      node test_engine.mjs --基线      # 有意改规则之后，重新生成基线（会打印新值）
 */
