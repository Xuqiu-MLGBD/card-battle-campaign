/* ============================ 一个确定性的脚本 bot ============================
   它只做"状态允许的、按固定优先级挑的第一个动作"，所以整局完全确定。
   它的作用有两个：① 走出一条标准对局；② 把命令序列记下来当基线。 */
function 下一步(状态) {
  if (状态.胜者) return null;
  if (状态.待选择) return { 类型: '选择', 席位: 状态.待选择.由, 选择: 0 };
  const 谁 = 状态.优先权;
  if (谁 !== 状态.主动) return { 类型: '让过', 席位: 谁 };
  const p = 状态.players[谁];
  for (let i = 0; i < p.手牌.length; i++) {
    const d = 卡表[p.手牌[i]];
    if (d && d.费 <= p.法力 && p.场上.length < 引擎.常量.场上上限) {
      return { 类型: '出牌', 席位: 谁, 手牌序号: i, 格子: p.场上.length };
    }
  }
  const 敌 = 谁 === 'p0' ? 'p1' : 'p0';
  const 我的 = 引擎.内部.场上随从(状态, 谁);
  const 敌的 = 引擎.内部.场上随从(状态, 敌);
  const 嘲讽 = 敌的.filter((u) => u.关键词.嘲讽);
  for (const u of 我的) {
    if (!u.可攻击 || u.冻结 || u.攻 <= 0) continue;
    /* 目标策略（这是 **bot 的策略**，不是规则）：有嘲讽先打嘲讽；否则只在"能一击换掉对方"
       时才去交易，换不掉就直接打脸。这条让标准对局既能出现随从互换/死亡，
       又不会两边站着互相磨到永远（早先"有随从就打随从"的写法能磨到 39 回合还不分胜负）。 */
    if (嘲讽.length) return { 类型: '攻击', 席位: 谁, 攻方: u.id, 目标: { 型: '随从', id: 嘲讽[0].id } };
    const 能换掉 = 敌的.find((e) => e.血 <= u.攻);
    const 目标 = 能换掉 ? { 型: '随从', id: 能换掉.id } : { 型: '英雄', 席位: 敌 };
    return { 类型: '攻击', 席位: 谁, 攻方: u.id, 目标 };
  }
  if (!p.英雄技能已用 && p.法力 >= 引擎.常量.英雄技能费) {
    return { 类型: '英雄技能', 席位: 谁, 目标: { 型: '英雄', 席位: 敌 } };
  }
  return { 类型: '让过', 席位: 谁 };
}

/* 跑一整局，顺便把每条命令的"状态不变式"验掉 */
function 走一局(种子, 命令上限 = 400) {
  let r = 开一局(种子);
  let 状态 = r.状态;
  const 事件表 = r.事件.slice();
  const 命令表 = [];
  let 步 = 0;
  let 变更不可重放的次数 = 0;
  while (步 < 命令上限) {
    const 命令 = 下一步(状态);
    if (!命令) break;
    const 前 = 状态;
    // 命令里不含"选择"时也允许被拒（脚本 bot 会试探），这里不管；只要求不抛错
    const out = 引擎.reduce(前, 命令, 环境);
    命令表.push(命令);
    /* ★ 不变量：新状态必须**恰好等于**把变更重放到原状态上 */
    if (JSON.stringify(事件.应用(前, out.变更)) !== JSON.stringify(out.状态)) 变更不可重放的次数++;
    const 状态问题 = 引擎.检查(out.状态);
    if (状态问题.length) { console.log('    [状态被写坏] ' + 状态问题.join('；')); fail++; }
    状态 = out.状态;
    事件表.push(...out.事件);
    步++;
  }
  return { 状态, 事件表, 命令表, 变更不可重放的次数, 步 };
}

