/* ============================ F 规则逐条 ============================ */

/* 手搓一个单位（测试用）。新战斗规则之后，单位上多了 攻耗/恢复/本回合攻击过 三个字段：
   前两个平常由 召唤() 从卡表固化，这里手搓就得自己带上，否则引擎读到 undefined 会当 0 处理。
   `上限` 用来造"残血但没死"的随从（验回合结束回复）；不给就 = 血。 */
function 造单位(id, 卡, 席位, 攻, 血, kw, 可攻击 = true, 体力, 上限) {
  const 表 = 卡表[卡] || {};
  const 攻耗 = 体力 && 体力.攻耗 !== undefined ? 体力.攻耗 : (表.攻耗 === undefined ? 1 : 表.攻耗);
  const 恢复 = 体力 && 体力.恢复 !== undefined ? 体力.恢复 : 攻耗;
  return {
    op: '置', 路径: ['单位', id],
    值: {
      id, 序: Number(String(id).slice(1)) || 1, 卡, 席位, 攻, 血, 血上限: (上限 === undefined ? 血 : 上限), 可攻击,
      冻结: false, 召唤回合: 1, 攻耗, 恢复, 本回合攻击过: false,
      关键词: Object.assign({ 嘲讽: false, 神圣护盾: false, 剧毒: false, 伤害后冻结: false, 反击: false }, kw || {}),
      亡语: []
    }
  };
}

/* 让"当前回合的主人"把回合结束掉：他自己让过 + 对手也让过。
   ⚠ 一条让过**不够**：让过只是把优先权交给对手，双方连续让过才推进回合
   （第一版测试就栽在这里 —— 以为一条让过就换回合，于是"回合结束回复"根本没触发）。 */
function 过一圈(状态) {
  const t = 引擎.reduce(状态, { 类型: '让过', 席位: 状态.优先权 }, 环境).状态;
  return 引擎.reduce(t, { 类型: '让过', 席位: t.优先权 }, 环境);
}

