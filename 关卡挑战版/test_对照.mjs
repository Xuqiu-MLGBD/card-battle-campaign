/* ============================ 小工具：造局面 + 跑一步 ============================ */
/* 手搓一个单位。新战斗规则之后，单位上还有 攻耗/恢复/本回合攻击过 三个字段：
   平常由 召唤() 从卡表固化；手搓就得自己带上（不给就从卡表取，取不到按 1）。 */
const 单位 = (id, 卡, 席位, 攻, 血, kw, 可攻击 = true, 体力, 上限) => {
  const 表 = 卡表[卡] || {};
  const 攻耗 = 体力 && 体力.攻耗 !== undefined ? 体力.攻耗 : (表.攻耗 === undefined ? 1 : 表.攻耗);
  const 恢复 = 体力 && 体力.恢复 !== undefined ? 体力.恢复 : 攻耗;
  return {
    op: '置', 路径: ['单位', id],
    值: {
      id, 序: Number(String(id).slice(1)) || 1, 卡, 席位, 攻, 血, 血上限: (上限 === undefined ? 血 : 上限), 可攻击,
      冻结: false, 召唤回合: 1, 攻耗, 恢复, 本回合攻击过: false,
      关键词: Object.assign({ 嘲讽: false, 神圣护盾: false, 剧毒: false, 伤害后冻结: false, 反击: false }, kw || {}),
      亡语: []
    }
  };
};
function 造(改动) {
  const r = EN.新建({ 种子: 7, 卡表, 血量: { p0: 30, p1: 30 }, 牌组: { p0: [], p1: [] }, 先手: 'p0' });
  return E.应用(r.状态, 改动);
}
function 跑(状态, 命令) { return EN.reduce(状态, 命令, 环境); }
function 让过到底(状态, 次数 = 8) {
  let t = 状态, 表 = [];
  for (let i = 0; i < 次数 && t.堆叠.length; i++) { const o = 跑(t, { 类型: '让过', 席位: t.优先权 }); 表.push(...o.事件); t = o.状态; }
  return { 状态: t, 事件: 表 };
}
/* 摆一排"双方各两个随从"，用来验战斗规则 */
