  function 回放(初始结果, 命令序列, 环境) {
    var 状态 = 初始结果.状态;
    var 事件 = 初始结果.事件.slice();
    var 变更 = 初始结果.变更.slice();
    for (var i = 0; i < 命令序列.length; i++) {
      var r = reduce(状态, 命令序列[i], 环境);
      状态 = r.状态;
      事件 = 事件.concat(r.事件);
      变更 = 变更.concat(r.变更);
    }
    return { 状态: 状态, 事件: 事件, 变更: 变更, 哈希: E.哈希(状态) };
  }

  /* 状态自身的几条不变量（不是规则，是"状态没被写坏"） */
  function 检查(状态) {
    var 问题 = [];
    for (var i = 0; i < 席位表.length; i++) {
      var s = 席位表[i], p = 状态.players[s];
      if (!p) { 问题.push('缺席位 ' + s); continue; }
      if (p.hp > p.血上限) 问题.push(s + ' 血量超过上限：' + p.hp + ' > ' + p.血上限);
      if (p.法力 > p.法力上限) 问题.push(s + ' 法力超过上限');
      if (p.法力上限 > 法力顶尖) 问题.push(s + ' 法力上限超过 ' + 法力顶尖);
      if (p.场上.length > 本场上限(状态)) 问题.push(s + ' 场上超过 ' + 本场上限(状态) + ' 张');
      if (p.手牌.length > 手牌上限) 问题.push(s + ' 手牌超过 ' + 手牌上限 + ' 张');
      var 见 = {};
      for (var j = 0; j < p.场上.length; j++) {
        var id = p.场上[j];
        if (见[id]) 问题.push(s + ' 场上有重复单位 ' + id);
        见[id] = true;
        if (!状态.单位[id]) 问题.push(s + ' 场上的 ' + id + ' 不在单位表里');
        else if (状态.单位[id].席位 !== s) 问题.push(id + ' 的席位与所属场地不一致');
      }
    }
    var keys = Object.keys(状态.单位);
    for (var k = 0; k < keys.length; k++) {
      var u = 状态.单位[keys[k]];
      if (u.血 <= 0) 问题.push('场上还留着一具尸体：' + u.id);   // 状态检查跑完不该有血 ≤ 0 的
      if (状态.players[u.席位].场上.indexOf(u.id) < 0) 问题.push(u.id + ' 没在它席位的场上');
    }
    if (状态.胜者 && 席位表.indexOf(状态.胜者) < 0) 问题.push('胜者不合法：' + 状态.胜者);
    return 问题;
  }

