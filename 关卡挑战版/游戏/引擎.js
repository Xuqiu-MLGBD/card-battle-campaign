  var E = G.HS_EVENT;
  if (!E) throw new Error('[引擎] 事件层（游戏/事件.js）必须先加载');

  var 版本 = 1;
  var 席位表 = ['p0', 'p1'];
  var 手牌上限 = 10;      // 上游 index.js 也是 10
  var 场上上限 = 5;       // **默认**部署位数；每局的真实上限在状态里（见 新建 的 配置.场上上限）
  var 法力顶尖 = 10;
  var 英雄技能费 = 2;
  var 英雄技能伤 = 1;

  function 敌方(席位) { return 席位 === 'p0' ? 'p1' : 'p0'; }
  function 是数组(x) { return Object.prototype.toString.call(x) === '[object Array]'; }
  /* 本局每侧几个部署位：**只认状态里的那一份**（新建 时按配置写进去），
     读不到才退回默认。规则层里所有"场地满没满"的判断都必须走这个函数，
     不许再直接读模块常量 —— 否则第一关（1 格）会被当成 5 格。 */
  function 本场上限(状态) { return (状态 && 状态.场上上限) || 场上上限; }

  /* ★★ 拒绝码表（2026-10-04，架构改进 A：照那份流程图的 `RuleError{ code, context }`）。
     口径：**code 给机器（日志/回放/本地化/UI 映射），原因给人（测试与控制台）**。
     为什么做成"原因前缀 → 码"的映射表、而不是去改那 28 个调用点：改动越小越不容易出错 ——
     一处补齐，全引擎的拒绝就自动带上码。放在**模块作用域**是因为导出要给自检用
     （第一版写在 合法() 里面，导出处直接 ReferenceError —— 这就是为什么"声明放哪儿"也要挑）。 */
  var 码表 = [
    ['命令没有类型', 'BAD_COMMAND'],
    ['对局已经结束', 'MATCH_OVER'],
    ['现在没有待选择的事项', 'NO_PENDING_CHOICE'],
    ['不该由你选', 'NOT_YOUR_CHOICE'],
    ['这个目标不在可选里', 'TARGET_NOT_ALLOWED'],
    ['这个目标不能选', 'TARGET_NOT_ALLOWED'],
    ['有事项等着先选完', 'CHOICE_PENDING'],
    ['现在不是你的优先权', 'NOT_YOUR_PRIORITY'],
    ['行动限本回合', 'ONCE_PER_TURN'],
    ['这个阶段不能行动', 'WRONG_PHASE'],
    ['手牌序号越界', 'CARD_NOT_IN_HAND'],
    ['场地已满', 'BOARD_FULL'],
    ['法力不够', 'INSUFFICIENT_MANA'],
    ['格子越界', 'BAD_SLOT'],
    ['攻方不在场', 'ATTACKER_GONE'],
    ['不是你的随从', 'NOT_YOUR_MINION'],
    ['这个随从这回合不能攻击', 'MINION_CANT_ATTACK'],
    ['被冻结的随从不能攻击', 'FROZEN'],
    ['攻击力为 0 打不出伤害', 'ZERO_ATTACK'],
    ['没有指定目标', 'NO_TARGET'],
    ['目标不在场', 'TARGET_GONE'],
    ['不能打自己的随从', 'CANT_HIT_OWN'],
    ['不能打自己的英雄', 'CANT_HIT_OWN_HERO'],
    ['目标型不认识', 'BAD_TARGET_KIND'],
    ['敌方有嘲讽随从', 'TAUNT_FIRST'],
    ['这个回合已经用过英雄技能', 'HERO_POWER_USED'],
    ['不认识的命令类型', 'UNKNOWN_COMMAND']
  ];
  function 取码(原因) {
    var s = String(原因 == null ? '' : 原因);
    for (var i = 0; i < 码表.length; i++) if (s.indexOf(码表[i][0]) === 0) return 码表[i][1];
    return 'UNKNOWN';
  }

  /* ============================== 随机 ==============================
     种子 + 游标 → 值。**不调用 Math.random**：同一个 (种子, 游标) 永远同一个值，
     所以整局可回放。用 xorshift 混合，够随机、够快、够确定。 */
  function 掷(种子, 游标) {
    var x = (种子 + Math.imul(游标, 2654435761)) >>> 0;
    x ^= x << 13; x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5; x >>>= 0;
    return { 值: x / 4294967296, 游标: 游标 + 1 };
  }

  /* 用状态里的 rng 洗一副牌（Fisher-Yates，随机数全部来自掷） */
  function 洗牌(数组, 种子, 游标) {
    var a = 数组.slice();
    var c = 游标;
    for (var i = a.length - 1; i > 0; i--) {
      var r = 掷(种子, c); c = r.游标;
      var j = Math.floor(r.值 * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return { 牌: a, 游标: c };
  }

  /* ============================== 施工（变更记录器）==============================
     状态**只通过变更前进**：这里在草稿上改，同时把每条改动记成一条可重放的操作。
     reduce 最后返回的 新状态 = 事件.应用(原状态, 变更) —— 也就是说
     "变更真是施工图"，不是事后补的 diff。测试里有一条不变量守着这件事。 */
  function 开工(原状态) {
    var 草稿 = E.深拷贝(原状态);
    var 变更表 = [];
    function 定位(路径) {
      var 父 = 草稿;
      for (var k = 0; k < 路径.length - 1; k++) 父 = 父[路径[k]];
      return 父;
    }
    return {
      草稿: function () { return 草稿; },
      变更: function () { return 变更表; },
      取: function (路径) {
        var 父 = 定位(路径);
        return 父[路径[路径.length - 1]];
      },
      置: function (路径, 值) {
        var 父 = 定位(路径), 末 = 路径[路径.length - 1];
        父[末] = 值;
        变更表.push({ op: '置', 路径: 路径.slice(), 值: E.深拷贝(值) });
      },
      删: function (路径) {
        var 父 = 定位(路径), 末 = 路径[路径.length - 1];
        if (是数组(父)) 父.splice(末, 1); else delete 父[末];
        变更表.push({ op: '删', 路径: 路径.slice() });
      },
      压入: function (路径, 值) {
        var 父 = 定位(路径), 末 = 路径[路径.length - 1];
        父[末].push(值);
        变更表.push({ op: '压入', 路径: 路径.slice(), 值: E.深拷贝(值) });
      },
      抽出: function (路径, 序号) {
        var 父 = 定位(路径), 末 = 路径[路径.length - 1];
        var 被抽 = 父[末].splice(序号, 1)[0];
        变更表.push({ op: '抽出', 路径: 路径.slice(), 序号: 序号 });
        return 被抽;
      }
    };
  }

  /* ============================== 新建一局 ==============================
     配置 = {
       种子, 卡表: {卡名: 定义}, 血量: {p0,p1},
       牌组: {p0:[卡名…], p1:[卡名…]}, 先手: 'p0', 先手手牌: 3, 后手手牌: 3
     }
     状态是**纯 JSON**（能 JSON.stringify 往返），所以快照/回放/比对都只是数据搬运。 */
  function 新建(配置) {
    var 种子 = 配置.种子 || 1;
    var 游标 = 0;
    var 状态 = {
      schemaVersion: 版本,
      seq: 0,
      回合: 1,
      主动: 配置.先手 || 'p0',
      阶段: '主要',                  // '主要' | '结束'
      优先权: 配置.先手 || 'p0',
      让过: { p0: false, p1: false },
      堆叠: [],
      待选择: null,
      胜者: null,
      单位序: 1,
      /* 本局**每侧能站几个**（用户 2026-10-03：第一关双方各 1 格、第二关 2 格……第五关 5 格；
         自由关分 1/3/5 三档）。以前它是模块常量，现在每局一份：页面按关卡的 `slots` 传进来，
         不传就是默认 5。它进状态是有意的 —— 换档位就是换一个开局配置，回放仍然可复现。 */
      场上上限: (配置.场上上限 || 场上上限),
      单位: {},
      卡表版本: E.哈希(配置.卡表 || {}),
      rng: { 种子: 种子, 游标: 0 },
      players: {}
    };
    for (var i = 0; i < 席位表.length; i++) {
      var s = 席位表[i];
      var 洗 = 洗牌(配置.牌组[s] || [], 种子, 游标);
      游标 = 洗.游标;
      状态.players[s] = {
        席位: s,
        hp: (配置.血量 && 配置.血量[s]) || 30,
        血上限: (配置.血量 && 配置.血量[s]) || 30,
        法力: 0,
        法力上限: 0,
        英雄技能已用: false,
        手牌: [],
        牌库: 洗.牌,
        墓地: [],
        场上: []
      };
    }
    状态.rng.游标 = 游标;

    /* 起手：先手 3 张、后手 3 张（后手多一张"补偿"这一版没做，见不相符清单）。
       发牌就走两条系统/规则事件，这样"起手也是事件溯源的一部分"，回放不必特判。 */
    var 日志 = E.建日志(0);
    var 施工 = 开工(状态);
    日志.开链('开局');
    日志.推({ 类别: E.类别.系统, 类型: '对局开始', 种子: 种子, 卡表版本: 状态.卡表版本 });
    var 先手 = 配置.先手 || 'p0';
    /* 第 1 回合也要有 1 点法力 —— "+1 法力上限"发生在"回合开始"里，
       而第 1 回合没有"上一回合"来推进它，所以这里补一次（上游起手也是 1/1）。 */
    施工.置(['players', 先手, '法力上限'], 1);
    施工.置(['players', 先手, '法力'], 1);
    推(日志, 施工, { 类别: E.类别.系统, 类型: '回合开始', 席位: 先手, 回合: 1, 法力上限: 1 });
    var 数量表 = {};
    数量表[先手] = (配置.先手手牌 || 3);
    数量表[敌方(先手)] = (配置.后手手牌 || 3);
    for (var j = 0; j < 席位表.length; j++) 抽牌(施工, 日志, 席位表[j], 数量表[席位表[j]], 状态.卡表);
    日志.闭链();
    施工.置(['seq'], 日志.序号());

    return {
      状态: E.应用(状态, 施工.变更()),
      事件: 日志.全部(),
      变更: 施工.变更(),
      待选择: null
    };
  }

  /* ============================== 读状态的小工具 ============================== */

  function 单位表(状态) { return 状态.单位; }
  function 找单位(状态, id) { return 状态.单位[id] || null; }

  function 对方场上(状态, 席位) {
    var 表 = [];
    var 全部 = 状态.单位;
    var keys = Object.keys(全部);
    for (var i = 0; i < keys.length; i++) {
      if (全部[keys[i]].席位 === 席位) 表.push(全部[keys[i]]);
    }
    /* 按落场序排（单位序是单调计数器）—— 迭代顺序必须是确定的，
       否则"先处理谁"随对象键序变化，末态哈希就不稳了。 */
    表.sort(function (a, b) { return a.序 - b.序; });
    return 表;
  }

  function 场上随从(状态, 席位) { return 对方场上(状态, 席位); }

  function 有嘲讽(状态, 席位) {
    var 表 = 场上随从(状态, 席位);
    for (var i = 0; i < 表.length; i++) if (表[i].关键词.嘲讽) return true;
    return false;
  }

  /* ============================== 目标 ============================== */

  function 卡定义(环境, 卡名) {
    var d = 环境 && 环境.卡表 && 环境.卡表[卡名];
    return d || { 名: 卡名, 费: 1, 攻: 1, 血: 1, 关键词: {}, 说明: '（卡表里没有这张）' };
  }

  function 目标描述(状态, 目标) {
    if (目标.型 === '英雄') return { 型: '英雄', 席位: 目标.席位, 名: 状态.players[目标.席位].名字 || (目标.席位 === 'p0' ? '我方英雄' : '敌方英雄') };
    var u = 找单位(状态, 目标.id);
    return { 型: '随从', id: 目标.id, 席位: u ? u.席位 : null, 名: u ? u.卡 : '？' };
  }

  /* 按效果的目标口径算出"这一刻可以选谁"。**引擎只画可选，不替玩家挑。** */
  function 可选目标(状态, 席位, 口径, 来源id) {
    var out = [];
    var 我 = 状态.players[席位], 敌 = 状态.players[敌方(席位)];
    var 我的 = 场上随从(状态, 席位), 敌的 = 场上随从(状态, 敌方(席位));
    function 加随从(表) { for (var i = 0; i < 表.length; i++) out.push({ 型: '随从', id: 表[i].id }); }
    if (口径 === '无') return out;
    if (口径 === '自身') { if (来源id) out.push({ 型: '随从', id: 来源id }); return out; }
    if (口径 === '自身英雄') { out.push({ 型: '英雄', 席位: 席位 }); return out; }
    if (口径 === '自身随从') { 加随从(我); return out; }
    if (口径 === '任意') { 加随从(我的); 加随从(敌的); out.push({ 型: '英雄', 席位: 'p0' }, { 型: '英雄', 席位: 'p1' }); return out; }
    if (口径 === '任意随从') { 加随从(我的); 加随从(敌的); return out; }
    if (口径 === '友方随从') { 加随从(我); return out; }
    if (口径 === '敌方随从') { 加随从(敌); return out; }
    if (口径 === '敌方嘲讽随从') {
      for (var i = 0; i < 敌的.length; i++) if (敌的[i].关键词.嘲讽) out.push({ 型: '随从', id: 敌的[i].id });
      return out;
    }
    if (口径 === '敌方英雄') { out.push({ 型: '英雄', 席位: 敌方(席位) }); return out; }
    if (口径 === '敌方角色') { 加随从(敌); out.push({ 型: '英雄', 席位: 敌方(席位) }); return out; }
    return out;
  }

  /* 这条效果要不要玩家点一个目标？
     召唤/抽牌不用；目标写成「无」或没写也不用。 */
  function 需目标(效) {
    if (!效 || !效.动作) return false;
    if (效.动作 === '召唤' || 效.动作 === '抽牌') return false;
    return !(效.目标 === undefined || 效.目标 === '无');
  }

  var 口径说法 = {
    '自身': '自己', '自身英雄': '自己的英雄', '自身随从': '自己的随从', '任意': '任意目标',
    '任意随从': '任意随从', '友方随从': '友方随从', '敌方随从': '敌方随从',
    '敌方嘲讽随从': '敌方带嘲讽的随从', '敌方英雄': '敌方英雄', '敌方角色': '敌方角色'
  };
  function 口径名(口径) { return 口径说法[口径] || String(口径); }

  function 在可选里(可选表, 目标) {
    for (var i = 0; i < 可选表.length; i++) {
      var it = 可选表[i];
      if (it.型 === 目标.型 && (目标.型 === '英雄' ? it.席位 === 目标.席位 : it.id === 目标.id)) return true;
    }
    return false;
  }

  /* ============================== 事件小工具 ============================== */

  function 推(日志, 施工, 事件) {
    var 条 = 日志.推(事件);
    /* 只有规则/触发/系统三类才改状态；表现类（fx）绝不进状态。 */
    if (条.类别 !== E.类别.表现) 条.改状态 = true;
    return 条;
  }

  /* ============================== 原语 ============================== */

  function 伤害(施工, 日志, 环境, 来源, 目标, 值, 原因, 父id) {
    var 状态 = 施工.草稿();
    var 实际 = 值;
    var 目标名;
    if (目标.型 === '英雄') {
      var p = 状态.players[目标.席位];
      目标名 = p.席位 === 'p0' ? '我方英雄' : '敌方英雄';
      var 新血 = p.hp - 实际;
      施工.置(['players', 目标.席位, 'hp'], 新血);
      推(日志, 施工, {
        类别: E.类别.规则, 类型: '英雄受伤', 席位: 目标.席位, 来源: 来源,
        目标: 目标.席位, 值: 实际, 剩余: 新血, 原因: 原因, 因: 父id
      });
      return { 落地: true, 剩余: 新血 };
    }
    var u = 找单位(状态, 目标.id);
    if (!u) return { 落地: false, 原因: '目标已不在场' };
    目标名 = u.卡;
    if (u.关键词.神圣护盾) {
      /* 神圣护盾：吸收一次伤害（并且这次吸收会消耗掉它）—— 与上游 attack.js 的判定一致 */
      施工.置(['单位', u.id, '关键词', '神圣护盾'], false);
      推(日志, 施工, {
        类别: E.类别.规则, 类型: '护盾抵消', 目标: u.id, 目标名: 目标名, 值: 实际,
        来源: 来源, 原因: 原因, 因: 父id
      });
      return { 落地: true, 剩余: u.血, 被护盾吸收: true };
    }
    var 新 = u.血 - 实际;
    /* 剧毒：只要被带剧毒的来源伤到，随从直接销毁（上游 Maexxna 的 Poisonous） */
    var 来源卡 = 来源 && 来源.卡名 ? 卡定义(环境, 来源.卡名) : null;
    if (来源卡 && 来源卡.关键词 && 来源卡.关键词.剧毒 && 原因 === '攻击') 新 = 0;
    施工.置(['单位', u.id, '血'], 新);
    if (来源卡 && 来源卡.关键词 && 来源卡.关键词.伤害后冻结) {
      施工.置(['单位', u.id, '冻结'], true);
    }
    推(日志, 施工, {
      类别: E.类别.规则, 类型: '随从受伤', 目标: u.id, 目标名: 目标名, 值: 实际,
      剩余: 新, 来源: 来源, 原因: 原因, 因: 父id
    });
    return { 落地: true, 剩余: 新 };
  }

  function 治疗(施工, 日志, 目标, 值, 父id) {
    var 状态 = 施工.草稿();
    if (目标.型 === '英雄') {
      var p = 状态.players[目标.席位];
      var 新血 = Math.min(p.血上限, p.hp + 值);
      施工.置(['players', 目标.席位, 'hp'], 新血);
      推(日志, 施工, { 类别: E.类别.规则, 类型: '英雄治疗', 席位: 目标.席位, 值: 新血 - p.hp, 剩余: 新血, 因: 父id });
      return;
    }
    var u = 找单位(状态, 目标.id);
    if (!u) return;
    var 顶 = u.血上限 + (u.加成血 || 0);
    var 新 = Math.min(顶, u.血 + 值);
    施工.置(['单位', u.id, '血'], 新);
    推(日志, 施工, { 类别: E.类别.规则, 类型: '随从治疗', 目标: u.id, 值: 新 - u.血, 剩余: 新, 因: 父id });
  }

  function 加成(施工, 日志, 目标, 攻, 血, 父id) {
    var 状态 = 施工.草稿();
    var u = 找单位(状态, 目标.id);
    if (!u) return;
    var 新攻 = u.攻 + 攻, 新血 = u.血 + 血;
    施工.置(['单位', u.id, '攻'], 新攻);
    施工.置(['单位', u.id, '血'], 新血);
    施工.置(['单位', u.id, '血上限'], u.血上限 + 血);
    推(日志, 施工, { 类别: E.类别.规则, 类型: '随从加成', 目标: u.id, 攻: 攻, 血: 血, 现攻: 新攻, 现血: 新血, 因: 父id });
  }

  function 冻结(施工, 日志, 目标, 父id) {
    var 状态 = 施工.草稿();
    if (目标.型 === '英雄') return;                 // 这一版英雄不能被冻结
    var u = 找单位(状态, 目标.id);
    if (!u) return;
    施工.置(['单位', u.id, '冻结'], true);
    推(日志, 施工, { 类别: E.类别.规则, 类型: '冻结', 目标: u.id, 目标名: u.卡, 因: 父id });
  }

  function 消灭(施工, 日志, 目标, 父id) {
    var 状态 = 施工.草稿();
    var u = 找单位(状态, 目标.id);
    if (!u) return;
    施工.置(['单位', u.id, '血'], 0);               // 交给状态检查去真的移除（一处实现）
    推(日志, 施工, { 类别: E.类别.规则, 类型: '标记消灭', 目标: u.id, 目标名: u.卡, 因: 父id });
  }

  /* 召唤：直接落场（对手牌来说，落场这一步在"出牌"里单独做；这里是效果造出来的召唤物） */
  function 召唤(施工, 日志, 环境, 席位, 卡名, 父id) {
    var 状态 = 施工.草稿();
    if (状态.players[席位].场上.length >= 本场上限(状态)) {
      推(日志, 施工, { 类别: E.类别.系统, 类型: '召唤失败', 席位: 席位, 卡: 卡名, 原因: '场地已满', 因: 父id });
      return null;
    }
    var 定 = 卡定义(环境, 卡名);
    var id = 'u' + 状态.单位序;
    施工.置(['单位序'], 状态.单位序 + 1);
    var 单位 = {
      id: id, 序: 状态.单位序, 卡: 卡名, 席位: 席位,
      攻: 定.攻, 血: 定.血, 血上限: 定.血,
      可攻击: !!(定.关键词 && 定.关键词.冲锋), 冻结: false,
      召唤回合: 状态.回合,
      /* 体力（用户 2026-10-03）：攻击要消耗 攻耗 点血；本回合没攻击则回合结束回 恢复 点血 */
      攻耗: (定.攻耗 === undefined ? 1 : 定.攻耗),
      恢复: (定.恢复 === undefined ? (定.攻耗 === undefined ? 1 : 定.攻耗) : 定.恢复),
      本回合攻击过: false,
      关键词: {
        嘲讽: !!(定.关键词 && 定.关键词.嘲讽),
        神圣护盾: !!(定.关键词 && 定.关键词.神圣护盾),
        剧毒: !!(定.关键词 && 定.关键词.剧毒),
        伤害后冻结: !!(定.关键词 && 定.关键词.伤害后冻结),
        反击: !!(定.关键词 && 定.关键词.反击)
      },
      亡语: E.深拷贝(定.亡语 || [])
    };
    施工.置(['单位', id], 单位);
    施工.压入(['players', 席位, '场上'], id);
    推(日志, 施工, { 类别: E.类别.规则, 类型: '召唤', 席位: 席位, 单位: id, 卡: 卡名, 攻: 单位.攻, 血: 单位.血, 因: 父id });
    return 单位;
  }

  function 抽牌(施工, 日志, 席位, 数量, 卡表) {
    for (var n = 0; n < 数量; n++) {
      var 状态 = 施工.草稿();
      var p = 状态.players[席位];
      if (!p.牌库.length) {
        /* 没有疲劳（用户 2026-10-02 定的）：牌打完就把墓地洗回去。洗牌用的随机也走 rng。 */
        if (!p.墓地.length) {
          推(日志, 施工, { 类别: E.类别.系统, 类型: '抽牌失败', 席位: 席位, 原因: '牌库与墓地都空' });
          continue;
        }
        var 洗 = 洗牌(p.墓地, 状态.rng.种子, 状态.rng.游标);
        施工.置(['players', 席位, '牌库'], 洗.牌);
        施工.置(['players', 席位, '墓地'], []);
        施工.置(['rng', '游标'], 洗.游标);
        推(日志, 施工, { 类别: E.类别.系统, 类型: '墓地洗回牌库', 席位: 席位, 张数: 洗.牌.length });
      }
      if (p.手牌.length >= 手牌上限) {
        推(日志, 施工, { 类别: E.类别.系统, 类型: '抽牌失败', 席位: 席位, 原因: '手牌已满' });
        continue;
      }
      var 卡 = p.牌库[0];
      施工.抽出(['players', 席位, '牌库'], 0);
      施工.压入(['players', 席位, '手牌'], 卡);
      /* 抽到什么牌是**隐藏信息**：对别家不可见（席位投影会把它换成占位串） */
      推(日志, 施工, {
        类别: E.类别.规则, 类型: '抽牌', 席位: 席位, 卡: 卡,
        剩余: p.牌库.length - 1, 隐藏字段: ['卡']
      });
    }
  }

  /* 执行一条效果规格。返回"是否还需要玩家选目标"。 */
  function 效果规格(定, 名) {
    if (!定) return null;
    if (名 === '战吼') return 定.战吼 || null;
    if (名 === '亡语') return 定.亡语 || null;
    return null;
  }

  function 执行效果(施工, 日志, 环境, 席位, 来源id, 效果, 目标, 父id) {
    if (效果.动作 === '伤害') 伤害(施工, 日志, 环境, { 单位: 来源id }, 目标, 效果.值, '效果', 父id);
    else if (效果.动作 === '治疗') 治疗(施工, 日志, 目标, 效果.值, 父id);
    else if (效果.动作 === '加成') 加成(施工, 日志, 目标, 效果.攻 || 0, 效果.血 || 0, 父id);
    else if (效果.动作 === '冻结') 冻结(施工, 日志, 目标, 父id);
    else if (效果.动作 === '消灭') 消灭(施工, 日志, 目标, 父id);
    else if (效果.动作 === '抽牌') 抽牌(施工, 日志, 席位, 效果.数量 || 1, 环境.卡表);
    else if (效果.动作 === '召唤') {
      for (var i = 0; i < (效果.数量 || 1); i++) 召唤(施工, 日志, 环境, 席位, 效果.卡, 父id);
    } else {
      推(日志, 施工, { 类别: E.类别.系统, 类型: '效果未实现', 动作: 效果.动作, 因: 父id });
    }
  }

  /* ============================== 状态检查（SBA）============================== */
  /* 「只要场上存在该发生的事，它立刻发生」——不看谁在等、不等人点确认。
     每次移交优先权之前都跑一遍，直到不动为止（死亡会触发亡语，亡语又可能造成死亡）。 */
  function 状态检查(施工, 日志, 环境) {
    var 轮 = 0;
    for (;;) {
      轮 += 1;
      if (轮 > 50) { 推(日志, 施工, { 类别: E.类别.系统, 类型: '状态检查超限' }); break; }
      var 状态 = 施工.草稿();
      var 变了 = false;

      /* ① 死亡（按落场序处理，顺序确定） */
      for (var i = 0; i < 席位表.length; i++) {
        var 表 = 场上随从(状态, 席位表[i]);
        for (var j = 0; j < 表.length; j++) {
          var u = 表[j];
          if (u.血 > 0) continue;
          var 事件 = 推(日志, 施工, { 类别: E.类别.规则, 类型: '死亡', 单位: u.id, 卡: u.卡, 席位: u.席位 });
          var 场上 = 状态.players[u.席位].场上;
          var 位置 = 场上.indexOf(u.id);
          if (位置 >= 0) 施工.抽出(['players', u.席位, '场上'], 位置);
          施工.删(['单位', u.id]);
          施工.压入(['players', u.席位, '墓地'], u.卡);
          变了 = true;
          /* 亡语：由死亡这个规则事件派生 —— 类别是"触发" */
          var 定 = 卡定义(环境, u.卡);
          var 亡语 = 定.亡语 || [];
          for (var k = 0; k < 亡语.length; k++) {
            推(日志, 施工, { 类别: E.类别.触发, 类型: '亡语触发', 单位: u.id, 卡: u.卡, 席位: u.席位, 因: 事件.id });
            执行效果(施工, 日志, 环境, u.席位, u.id, 亡语[k], 亡语[k].目标 === '自身' ? { 型: '随从', id: u.id } : { 型: '英雄', 席位: u.席位 }, 事件.id);
          }
        }
      }

      /* ② 胜负：英雄血量归零。**只在这里判**（一处实现），别处不许各自判一次 */
      for (var m = 0; m < 席位表.length; m++) {
        var s = 席位表[m];
        if (状态.players[s].hp <= 0 && !状态.胜者) {
          施工.置(['胜者'], 敌方(s));
          推(日志, 施工, { 类别: E.类别.规则, 类型: '胜负', 胜者: 敌方(s), 败者: s });
          变了 = true;
        }
      }
      if (!变了) break;
    }
  }

