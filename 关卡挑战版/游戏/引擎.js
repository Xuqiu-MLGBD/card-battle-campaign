  function 压栈(施工, 日志, 项) {
    施工.压入(['堆叠'], 项);
    施工.置(['让过'], { p0: false, p1: false });
    /* 压栈之后**对手先拿到优先权**：这就是"可以在它生效前再插一条"的入口 */
    施工.置(['优先权'], 敌方(项.席位));
    推(日志, 施工, { 类别: E.类别.系统, 类型: '压栈', 堆叠项: 项.种类, 席位: 项.席位, 描述: 项.描述 || '' });
    推(日志, 施工, { 类别: E.类别.系统, 类型: '优先权', 席位: 敌方(项.席位) });
  }

  /* 结算栈顶。返回事件 id，供调用方当"血缘"用。 */
  function 结算栈顶(施工, 日志, 环境) {
    var 状态 = 施工.草稿();
    if (!状态.堆叠.length) return null;
    var 项 = 状态.堆叠[状态.堆叠.length - 1];
    var 事件 = 推(日志, 施工, { 类别: E.类别.系统, 类型: '开始结算', 堆叠项: 项.种类, 席位: 项.席位, 描述: 项.描述 || '' });
    施工.抽出(['堆叠'], 状态.堆叠.length - 1);

    if (项.种类 === '攻击') {
      var 攻方 = 找单位(施工.草稿(), 项.攻方);
      if (!攻方) {
        推(日志, 施工, { 类别: E.类别.系统, 类型: '落空', 堆叠项: '攻击', 原因: '攻方已不在场', 因: 事件.id });
      } else {
        攻击结算(施工, 日志, 环境, 攻方, 项.目标, 事件.id);
      }
    } else if (项.种类 === '战吼') {
      var 来源 = 找单位(施工.草稿(), 项.来源);
      if (!来源) {
        推(日志, 施工, { 类别: E.类别.系统, 类型: '落空', 堆叠项: '战吼', 原因: '来源已不在场', 因: 事件.id });
      } else {
        /* 逐条效果走：每条**重新验目标**——响应期间目标没了就这一条落空（堆叠真正的意义） */
        for (var i = 0; i < 项.效果表.length; i++) {
          var 条 = 项.效果表[i];
          if (条.落空) {
            推(日志, 施工, { 类别: E.类别.系统, 类型: '落空', 堆叠项: '战吼', 原因: '当时就没有合法目标', 因: 事件.id });
            continue;
          }
          if (需目标(条.效果)) {
            var 现在的可选 = 可选目标(施工.草稿(), 项.席位, 条.效果.目标, 项.来源);
            if (!条.目标 || !在可选里(现在的可选, 条.目标)) {
              推(日志, 施工, { 类别: E.类别.系统, 类型: '落空', 堆叠项: '战吼', 原因: '目标已不合法', 因: 事件.id });
              continue;
            }
          }
          执行效果(施工, 日志, 环境, 项.席位, 项.来源, 条.效果, 条.目标, 事件.id);
        }
      }
    }
    return 事件.id;
  }

  /* 攻击结算（用户 2026-10-03 定的新规则，与炉石那套**不一样**，逐条写清）：

     ① 攻方把自己的攻击力打到目标身上（这部分没变）。
     ② **默认没有任何反击**：打对方随从，攻方不会再挨对方的攻击力。
        只有目标带「反击」词条时才还手（整个卡表里只有 3 张：Maexxna / The Black Knight / Sludge Belcher）。
     ③ 带「反击」时，"**打完还活着才反击**"是**正确写法** —— 目标被这一击打死了就不还手。
        ⚠ 这条以前被改过一版：那时按炉石"伤害同时发生"做，先记下守方攻击力、哪怕守方死了也照样打回来
        （对照清单第 4 条当时还专门断言过）。**现在按用户的新规则反过来了**，所以那个"先记攻击力"
        的写法已经删掉，改回"活着才反击"。理由：反击是**目标的词条能力**，不是"互相同时造成的伤害" ——
        一个被打死的单位没有机会发动它的能力。
     ④ 攻方要**付代价**：消耗自己的 `攻耗` 点生命值（红色 -x 就是它）。这不是伤害、不会触发
        神圣护盾/剧毒那套，就是"体力"花掉了；**花到 0 就死**（用户确认「能打空就死」）。
     ⑤ 攻方本回合标记为"攻击过" → 这一回合结束时**不会**触发回复（见 回合推进）。

     顺序：先打目标 → 目标带反击且还活着才反打 → 攻方付体力。这样"攻方被自己的体力打死"时，
     它造成的伤害已经落地了（不会因为自己死了就白打）。 */
  function 攻击结算(施工, 日志, 环境, 攻方, 目标, 父id) {
    var 反伤 = 伤害(施工, 日志, 环境, { 单位: 攻方.id, 卡名: 攻方.卡 }, 目标, 攻方.攻, '攻击', 父id);

    /* ③ 只有"目标带反击、且挨完这一击还活着"才还手 */
    if (目标.型 === '随从') {
      var 守 = 找单位(施工.草稿(), 目标.id);
      if (守 && 守.关键词.反击 && 守.血 > 0 && 守.攻 > 0) {
        推(日志, 施工, { 类别: E.类别.触发, 类型: '反击触发', 单位: 守.id, 卡: 守.卡, 攻: 守.攻, 因: 父id });
        伤害(施工, 日志, 环境, { 单位: 守.id, 卡名: 守.卡 }, { 型: '随从', id: 攻方.id }, 守.攻, '反击', 父id);
      }
    }

    /* ④ 攻方付体力（标记攻击过 → 本回合不再回复）。攻耗 是召唤时从卡表固化到单位上的。 */
    付体力(施工, 日志, 找单位(施工.草稿(), 攻方.id), 攻方.攻耗, 父id);
    施工.置(['单位', 攻方.id, '本回合攻击过'], true);
    return 反伤;
  }

  /* 付体力：直接扣血，**不走 伤害() 原语** —— 它不是伤害（不触发护盾、不吃剧毒、不算"受伤"）。
     扣到 ≤ 0 就交给状态检查去移除（一处实现）。 */
  function 付体力(施工, 日志, 单位, 数值, 父id) {
    if (!单位) return;
    var 值 = (数值 === null || 数值 === undefined) ? 0 : 数值;
    推(日志, 施工, { 类别: E.类别.规则, 类型: '体力消耗', 单位: 单位.id, 卡: 单位.卡, 值: 值, 因: 父id });
    if (!值) return;
    施工.置(['单位', 单位.id, '血'], 单位.血 - 值);
  }

  /* 一次让过之后的推进：双方连续让过 → 结算栈顶 / 推进回合 */
  function 让过推进(施工, 日志, 环境, 席位) {
    施工.置(['让过', 席位], true);
    推(日志, 施工, { 类别: E.类别.系统, 类型: '让过', 席位: 席位 });
    var 状态 = 施工.草稿();
    if (!(状态.让过.p0 && 状态.让过.p1)) {
      施工.置(['优先权'], 敌方(席位));
      推(日志, 施工, { 类别: E.类别.系统, 类型: '优先权', 席位: 敌方(席位) });
      return;
    }
    /* 双方都让过 */
    施工.置(['让过'], { p0: false, p1: false });
    if (状态.堆叠.length) {
      var 链 = 日志.推({ 类别: E.类别.系统, 类型: '链', 描述: '结算栈顶' });
      结算栈顶(施工, 日志, 环境);
      状态检查(施工, 日志, 环境);
      施工.置(['优先权'], 状态.主动);
      推(日志, 施工, { 类别: E.类别.系统, 类型: '优先权', 席位: 状态.主动 });
    } else {
      /* 栈空且都让过 → 推进：主动方结束回合 */
      回合推进(施工, 日志, 环境);
    }
  }

  function 回合推进(施工, 日志, 环境) {
    var 状态 = 施工.草稿();
    if (状态.胜者) return;
    推(日志, 施工, { 类别: E.类别.系统, 类型: '回合结束', 席位: 状态.主动, 回合: 状态.回合 });

    /* ★ 回合结束时的**体力回复**（用户 2026-10-03）：
       「如果本回合不执行攻击，在回合结束时可以恢复的生命值（绿色 +x）」
       —— 只算**这个回合的主人**的随从，而且只补**本回合没攻击过**的那些，最多回满血上限。
       先回血、再解冻（两者不互相影响，只是顺序写死好读）。 */
    var 己方 = 场上随从(状态, 状态.主动);
    for (var i = 0; i < 己方.length; i++) {
      var u = 己方[i];
      if (u.本回合攻击过) continue;                      // 打过就不回
      var 上限 = u.血上限;
      var 能回 = 上限 - u.血;
      if (能回 <= 0 || !u.恢复) continue;                 // 满血 / 恢复为 0 → 什么都不做
      var 实际 = Math.min(能回, u.恢复);
      施工.置(['单位', u.id, '血'], u.血 + 实际);
      推(日志, 施工, { 类别: E.类别.规则, 类型: '体力回复', 单位: u.id, 卡: u.卡, 值: 实际, 现有: u.血 + 实际 });
    }

    /* 结束阶段：冻结在回合结束时解冻（和炉石一致：冻一个回合，不是永久） */
    for (var j = 0; j < 己方.length; j++) {
      if (己方[j].冻结) 施工.置(['单位', 己方[j].id, '冻结'], false);
    }
    var 下一个 = 敌方(状态.主动);
    施工.置(['主动'], 下一个);
    施工.置(['回合'], 状态.回合 + 1);
    施工.置(['阶段'], '主要');
    施工.置(['优先权'], 下一个);
    施工.置(['让过'], { p0: false, p1: false });

    /* 回合开始：法力上限 +1（至多 10）→ 回满法力 → 抽一张 → 己方随从解除召唤失调 + 清"攻击过"标记 */
    var p = 施工.草稿().players[下一个];
    var 新上限 = Math.min(法力顶尖, p.法力上限 + 1);
    施工.置(['players', 下一个, '法力上限'], 新上限);
    施工.置(['players', 下一个, '法力'], 新上限);
    施工.置(['players', 下一个, '英雄技能已用'], false);
    推(日志, 施工, { 类别: E.类别.系统, 类型: '回合开始', 席位: 下一个, 回合: 施工.草稿().回合, 法力上限: 新上限 });
    var 新方 = 场上随从(施工.草稿(), 下一个);
    for (var k = 0; k < 新方.length; k++) {
      施工.置(['单位', 新方[k].id, '可攻击'], true);
      施工.置(['单位', 新方[k].id, '本回合攻击过'], false);   // 新回合 → "本回合"重新计
    }
    抽牌(施工, 日志, 下一个, 1, 环境.卡表);
    状态检查(施工, 日志, 环境);
  }

  /* ============================== 合法性 ============================== */

  function 合法(状态, 命令, 环境) {
    /* ★★ 拒绝码表（2026-10-04，架构改进 A：照那份流程图的 `RuleError{ code, context }`）。
     口径：**code 给机器（日志/回放/本地化/UI 映射），原因给人（测试与控制台）**。
     为什么用"原因前缀 → 码"的映射表、而不是去改那 28 个调用点：改动越小越不容易出错 ——
     一处补齐，全引擎的拒绝都自动带上码；`上下文` 仍由调用点按需补（暂时留空也不影响）。
     下游怎么用（见 游戏/文案.js）：界面拿 code 去查中文模板，日志只记 code + context。 */
  /* 否定回答：**每一条拒绝都带码**（自检 ㉛ 会抽样验"带码"，缺码就是回归）。
     码表在模块作用域（见文件上方 码表/取码）—— 因为导出要给自检用，嵌在 合法() 里就取不到了。 */
  function 否(原因, 上下文) { return { 合法: false, 原因: 原因, 码: 取码(原因), 上下文: 上下文 || null }; }
    if (!命令 || !命令.类型) return 否('命令没有类型');
    if (状态.胜者) return 否('对局已经结束');

    if (命令.类型 === '选择') {
      if (!状态.待选择) return 否('现在没有待选择的事项');
      if (状态.待选择.由 !== 命令.席位) return 否('不该由你选');
      var 选 = 解析目标(命令, 状态.待选择.可选);
      /* 必须真的在可选里 —— 不然"选一个不存在的目标"会被放行 */
      if (!选 || !在可选里(状态.待选择.可选, 选)) return 否('这个目标不在可选里');
      return { 合法: true, 目标: 选 };
    }
    if (状态.待选择) return 否('有事项等着先选完（' + 状态.待选择.提示 + '）');

    if (命令.类型 === '让过') {
      if (状态.优先权 !== 命令.席位) return 否('现在不是你的优先权');
      return { 合法: true };
    }

    var 主动方 = 状态.主动;
    /* 行动限本回合：只有本回合的主动方、且拿着优先权时才能做事 */
    if (命令.类型 === '出牌' || 命令.类型 === '攻击' || 命令.类型 === '英雄技能') {
      if (状态.优先权 !== 命令.席位) return 否('现在不是你的优先权');
      if (命令.席位 !== 主动方) return 否('行动限本回合：现在是 ' + 主动方 + ' 的回合');
      if (状态.阶段 !== '主要') return 否('这个阶段不能行动');
    }

    if (命令.类型 === '出牌') {
      var p = 状态.players[命令.席位];
      if (typeof 命令.手牌序号 !== 'number' || 命令.手牌序号 < 0 || 命令.手牌序号 >= p.手牌.length) return 否('手牌序号越界');
      if (p.场上.length >= 本场上限(状态)) return 否('场地已满（上限 ' + 本场上限(状态) + '）');
      var 卡名 = p.手牌[命令.手牌序号];
      var 定 = 卡定义(环境, 卡名);
      if (定.费 > p.法力) return 否('法力不够（' + 卡名 + ' 要 ' + 定.费 + '，只有 ' + p.法力 + '）');
      if (typeof 命令.格子 === 'number' && (命令.格子 < 0 || 命令.格子 >= 本场上限(状态))) return 否('格子越界');
      return { 合法: true, 卡名: 卡名, 定: 定 };
    }

    if (命令.类型 === '攻击') {
      var 攻 = 找单位(状态, 命令.攻方);
      if (!攻) return 否('攻方不在场');
      if (攻.席位 !== 命令.席位) return 否('不是你的随从');
      if (!攻.可攻击) return 否('这个随从这回合不能攻击（召唤失调或已经打过）');
      if (攻.冻结) return 否('被冻结的随从不能攻击');
      if (攻.攻 <= 0) return 否('攻击力为 0 打不出伤害');
      var 目标 = 命令.目标;
      if (!目标 || !目标.型) return 否('没有指定目标');
      if (目标.型 === '随从') {
        var t = 找单位(状态, 目标.id);
        if (!t) return 否('目标不在场');
        if (t.席位 === 命令.席位) return 否('不能打自己的随从');
      } else if (目标.型 === '英雄') {
        if (目标.席位 === 命令.席位) return 否('不能打自己的英雄');
      } else return 否('目标型不认识');
      /* 嘲讽：敌方有嘲讽随从时，必须先打嘲讽（上游玩家侧漏了这条，引擎补上） */
      var 敌 = 敌方(命令.席位);
      if (有嘲讽(状态, 敌)) {
        var 是指向嘲讽 = 目标.型 === '随从' && 找单位(状态, 目标.id).关键词.嘲讽;
        if (!是指向嘲讽) return 否('敌方有嘲讽随从，必须先打它');
      }
      return { 合法: true };
    }

    if (命令.类型 === '英雄技能') {
      var me = 状态.players[命令.席位];
      if (me.英雄技能已用) return 否('这个回合已经用过英雄技能');
      if (me.法力 < 英雄技能费) return 否('法力不够（英雄技能要 ' + 英雄技能费 + '）');
      var 可选 = 可选目标(状态, 命令.席位, '任意', null);
      var 目标2 = 命令.目标;
      if (目标2 && 目标2.型 === '随从') {
        var uu = 找单位(状态, 目标2.id);
        if (!uu) return 否('目标不在场');
      }
      if (!目标2 || !在可选里(可选, 目标2)) return 否('这个目标不能选');
      return { 合法: true };
    }

    return 否('不认识的命令类型：' + 命令.类型);
  }

  function 解析目标(命令, 可选表) {
    if (命令.目标 && 命令.目标.型) return 命令.目标;
    if (typeof 命令.选择 === 'number' && 可选表[命令.选择]) return 可选表[命令.选择];
    return null;
  }

  /* ============================== reduce ============================== */

  function reduce(状态, 命令, 环境) {
    环境 = 环境 || {};
    var 判定 = 合法(状态, 命令, 环境);

    var 日志 = E.建日志(状态.seq);
    var 施工 = 开工(状态);

    if (!判定.合法) {
      /* 被拒绝也要**入日志**（带原因）：否则"我明明点了却没反应"就查不出来。
         注意：拒绝不改状态，所以 变更 = 只有 seq 往前一格（日志要连续）。 */
      日志.开链('拒绝');
      var 拒 = 推(日志, 施工, {
        类别: E.类别.系统, 类型: '命令被拒', 命令: 命令 ? 命令.类型 : null, 席位: 命令 ? 命令.席位 : null, 原因: 判定.原因
      });
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      return {
        状态: E.应用(状态, 施工.变更()),
        事件: 日志.全部(),
        变更: 施工.变更(),
        待选择: 状态.待选择,
        被拒: 判定.原因,
        拒绝事件: 拒.id
      };
    }

    var 席位 = 命令.席位;
    日志.开链(命令.类型 + (席位 ? '@' + 席位 : ''));

    /* ---- 待选择 → 选择：把草稿命令补上目标，继续走原来那条路 ---- */
    if (命令.类型 === '选择') {
      var 待 = E.深拷贝(状态.待选择);
      施工.置(['待选择'], null);
      推(日志, 施工, { 类别: E.类别.系统, 类型: '已选择', 席位: 席位, 目标: E.稳定串(判定.目标) });
      var 草稿命令 = 待.草稿;
      草稿命令.席位 = 草稿命令.席位 || 席位;
      /* 只可能是出牌：需要玩家选目标的只有战吼（羊入虎口的目标由出牌自己接着问） */
      var 还要选 = 出牌(施工, 日志, 环境, 草稿命令, { 草稿: 待.草稿, 目标: 判定.目标 });
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      if (还要选) {
        return {
          状态: E.应用(状态, 施工.变更()),
          事件: 日志.全部(), 变更: 施工.变更(), 待选择: 施工.草稿().待选择
        };
      }
      return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
    }

    if (命令.类型 === '让过') {
      让过推进(施工, 日志, 环境, 席位);
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
    }

    if (命令.类型 === '出牌') {
      var 需选 = 出牌(施工, 日志, 环境, 命令, null);
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      if (需选) {
        return {
          状态: E.应用(状态, 施工.变更()),
          事件: 日志.全部(),
          变更: 施工.变更(),
          待选择: 施工.草稿().待选择
        };
      }
      return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
    }

    if (命令.类型 === '攻击') {
      var 攻 = 找单位(状态, 命令.攻方);
      /* 「这一回合已经打过了」是**宣布时就付的代价**，不是结算时才付 ——
         不然同一个小兵能在栈上连压十几次（都是合法的），栈永远清不完。
         这跟"付费不用堆叠"是同一条道理：出牌也是一压栈就扣法力。 */
      施工.置(['单位', 攻.id, '可攻击'], false);
      压栈(施工, 日志, {
        种类: '攻击', 席位: 席位, 攻方: 攻.id, 目标: 命令.目标,
        描述: (攻.卡) + ' → ' + (命令.目标.型 === '英雄' ? '英雄' : (找单位(状态, 命令.目标.id) || {}).卡)
      });
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
    }

    if (命令.类型 === '英雄技能') {
      var me = 施工.草稿().players[席位];
      施工.置(['players', 席位, '法力'], me.法力 - 英雄技能费);
      施工.置(['players', 席位, '英雄技能已用'], true);
      推(日志, 施工, { 类别: E.类别.规则, 类型: '英雄技能', 席位: 席位, 费: 英雄技能费 });
      伤害(施工, 日志, 环境, { 英雄技能: 席位 }, 命令.目标, 英雄技能伤, '英雄技能', null);
      状态检查(施工, 日志, 环境);
      日志.闭链();
      施工.置(['seq'], 日志.序号());
      return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
    }

    /* 理论上到不了这里（合法() 已经把类型都盖住了） */
    日志.闭链();
    施工.置(['seq'], 日志.序号());
    return 收尾(状态, 施工, 日志, 环境, 命令, 判定);
  }

  /* 出牌。分两拍：
     第一拍：把战吼**每条效果的目标**都定下来。只有一种合法选的（比如"敌方英雄"）就自动绑上
             （那不是"替玩家猜"，是唯一的合法解）；有多种才问玩家 —— 问的时候**不改状态**，
             只挂一个 待选择，等界面把 {类型:'选择'} 送回来。
     第二拍：扣法力、移出手牌、落场、把战吼压栈。
     返回「还要继续选」时给出待选择对象；否则返回 null。 */
  function 出牌(施工, 日志, 环境, 命令, 待) {
    var 状态 = 施工.草稿();
    var 席位 = 命令.席位;
    var p = 状态.players[席位];
    var 卡名 = p.手牌[命令.手牌序号];
    var 定 = 卡定义(环境, 卡名);
    var 战吼 = 定.战吼 || [];
    var 目标表;

    if (!待) {
      目标表 = [];
      for (var i = 0; i < 战吼.length; i++) {
        var 效 = 战吼[i];
        if (!需目标(效)) { 目标表.push({ 目标: null, 落空: false }); continue; }
        var 可选 = 可选目标(状态, 席位, 效.目标, null);
        if (!可选.length) 目标表.push({ 目标: null, 落空: true });
        else if (可选.length === 1) 目标表.push({ 目标: 可选[0], 落空: false });
        else 目标表.push({ 目标: null, 落空: false, 待选: true });
      }
    } else {
      目标表 = E.深拷贝(待.草稿.目标表);
      var 表 = 目标表[待.草稿.效果下标];
      表.目标 = 待.目标;
      delete 表.待选;
      /* 这张卡如果还有第二条要选的效果，接着问（现在只有"选一次"的卡，但机制是通的） */
      for (var m = 0; m < 目标表.length; m++) {
        if (!目标表[m].待选) continue;
        var 效2 = 战吼[m];
        推(日志, 施工, { 类别: E.类别.系统, 类型: '等待选择', 席位: 席位, 提示: 定.名 + ' 还有一条战吼要选目标' });
        施工.置(['待选择'], {
          类型: '选目标', 由: 席位, 提示: 定.名 + ' 的战吼：选一个' + 口径名(效2.目标),
          可选: 可选目标(状态, 席位, 效2.目标, null),
          草稿: { 类型: '出牌', 席位: 席位, 手牌序号: 命令.手牌序号, 格子: 命令.格子, 效果下标: m, 目标表: 目标表 }
        });
        return 施工.草稿().待选择;
      }
    }

    /* 还有没绑好的目标 → 现在是"第一拍"，把待选择挂上、原样返回（状态只多了这个待选择） */
    for (var k = 0; k < 目标表.length; k++) {
      if (!目标表[k].待选) continue;
      var 效3 = 战吼[k];
      推(日志, 施工, { 类别: E.类别.系统, 类型: '等待选择', 席位: 席位, 提示: 定.名 + ' 的战吼要选目标' });
      施工.置(['待选择'], {
        类型: '选目标', 由: 席位, 提示: 定.名 + ' 的战吼：选一个' + 口径名(效3.目标),
        可选: 可选目标(状态, 席位, 效3.目标, null),
        草稿: { 类型: '出牌', 席位: 席位, 手牌序号: 命令.手牌序号, 格子: 命令.格子, 效果下标: k, 目标表: 目标表 }
      });
      return 施工.草稿().待选择;
    }
    /* 注意：这里**不改传进来的命令对象** —— 引擎只读命令。
       目标表通过堆叠项与 待选择.草稿 传递，不往调用方的对象上挂东西。 */

    /* 扣法力、移出手牌、落场 */
    施工.置(['players', 席位, '法力'], p.法力 - 定.费);
    var 抽出 = 施工.抽出(['players', 席位, '手牌'], 命令.手牌序号);
    推(日志, 施工, { 类别: E.类别.规则, 类型: '出牌', 席位: 席位, 卡: 抽出, 费: 定.费, 格子: 命令.格子 });
    var 单位 = 召唤(施工, 日志, 环境, 席位, 抽出, null);

    /* 战吼：压栈（对手先拿到优先权 → 可以在它生效前插一条）——
       这样"打中那一拍才结算"是规则的自然结果，不是演出硬凑的。
       结算前会**重新验一遍目标**：目标在响应期间没了，这条效果就落空。 */
    if (单位 && 战吼.length) {
      var 效果表 = [];
      for (var j = 0; j < 战吼.length; j++) 效果表.push({ 效果: 战吼[j], 目标: 目标表[j] ? 目标表[j].目标 : null, 落空: !!(目标表[j] && 目标表[j].落空) });
      压栈(施工, 日志, {
        种类: '战吼', 席位: 席位, 来源: 单位.id, 效果表: 效果表,
        描述: 单位.卡 + ' 的战吼'
      });
    }
    return null;
  }

  function 收尾(原状态, 施工, 日志, 环境, 命令, 判定) {
    状态检查(施工, 日志, 环境);
    if (命令.类型 !== '选择') 施工.置(['seq'], 日志.序号());
    return {
      状态: E.应用(原状态, 施工.变更()),
      事件: 日志.全部(),
      变更: 施工.变更(),
      待选择: 施工.草稿().待选择,
      拒绝: null
    };
  }

  /* ============================== 视图（席位投影：状态侧）============================== */

  /* 对手手牌与双方牌库都是隐藏信息 —— **从数据层就分开**，别指望界面自觉不画。
     给界面/bot 的一律是投影后的视图；只有引擎与存档看得到全量状态。 */
  function 视图(状态, 席位) {
    var v = E.深拷贝(状态);
    for (var i = 0; i < 席位表.length; i++) {
      var s = 席位表[i];
      if (s !== 席位) v.players[s].手牌 = v.players[s].手牌.map(function () { return '？'; });
      v.players[s].牌库 = v.players[s].牌库.map(function () { return '？'; });
      v.players[s].墓地 = v.players[s].墓地;
    }
    v.观看席位 = 席位;
    return v;
  }

