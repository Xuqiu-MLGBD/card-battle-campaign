/* 关卡挑战版 · 权威状态 + revision（游戏/状态.js —— 架构改进 B）
 * ==========================================================================
 * 那份流程图里最要紧的一条：**权威状态 ≠ 展示状态**。
 *   权威状态是规则真相（每次变更 revision + 1，产出事件）；
 *   展示状态可以**滞后**在动画后面；"跳过动画" = **强制追平到最新 revision**。
 *
 * 我们现在离它有多远：**DOM 既是权威也是展示** —— 攻/血/手牌/法力都在 DOM 文本里。
 * 于是这一周踩的坑大半从这里来：页内重开要"清一堆瞬时图层"、演出与状态不同步、
 * 跳过动画没法校验（没有权威可比）、检错层做不了 ATOMIC/REVISION/PRESENTATION 那几条。
 *
 * ★ 为什么这一轮是"**观察式权威**"（过渡形态，写明理由）：
 *   把每个游戏动作都翻译成"变更"要先把整局建模（单位 id、格子、区域…），那是阶段 C 的活；
 *   现在我们已经有**唯一意图出口**（改进 F）与**结构化拒绝**（A），所以先做**能立刻兑现价值**的那半：
 *     在**提交点**（出牌后 / 攻击结算后 / 回合边界 / 资源变化后）采一份权威状态，
 *     与上一次**求差**得到变更与事件，revision + 1；
 *     平时（非提交点）任何 DOM 变化都会被 `对账()` 抓到 → 那就是"两套真相"现形的时刻。
 *   等阶段 C 把动作都翻译成变更时，**只需要把"采 + 求差"换成"直接提交变更"**，上层（revision/事件/对账/追平）一个字都不用改。
 *
 * 本文件**不碰 DOM**：取值与重画都由界面注入（`取` / `画`）—— 于是核心逻辑能在 node 里直接测。
 * 相位/字段名与 游戏/事件.js 的口径保持一致（置/删/压入/抽出），将来换成真变更时不必改名。
 */
(function (W) {
  'use strict';
  if (W.HS_STATE) return;

  var 版本 = 1;

  /* 采集器返回的形状（界面负责从 DOM 取，这里只定义"权威状态长什么样"）：
     {
       回合, 法力, 法力上限,
       单位: { 'playerCardInPlay0': {id, 卡, 攻, 血, 攻耗, 恢复}, ... },
       席位: { player: { 英雄血, 场上: ['playerCardInPlay0', ...] },
               enemy:  { 英雄血, 场上: [...] } },
       手牌: ['卡名', ...]
     }

     ★ 2026-10-04 修正（一个真缺陷，由提交层自己抓到）：
       原来 场上 是**对象数组**，而 `求差/应用` 是按**引擎那套形状**写的
       （`压入/抽出` 拿 id、单位字段变化写成 `置 ['单位', id]`）——
       于是"把变更重放回旧状态"永远不等于新状态，`ATOMIC_VIOLATION` 在**正常对局里乱报**
       （实测：敌方回合结束一次、攻击结算一次），而报告里只有 `{原因, revision}`，看不出差在哪。
       现在把权威状态的形状**对齐引擎**（`单位` 映射 + `场上` 只放 id），三件事一起兑现：
         ① 求差/应用自洽 → 原子性检查才有意义（它是真的在验"施工图能否还原成品"）；
         ② 变更与事件变成**可回放**的（原来是"说了个单位变化、但那个路径不存在"）；
         ③ 阶段 C（引擎成为唯一写入路径）就只剩"把采+求差换成直接提交变更"这一步 —— 形状已经一样了。 */
  function 空() {
    return {
      版本: 版本, revision: 0, 展示revision: 0, 回合: 1,
      法力: 0, 法力上限: 0,
      单位: {},
      席位: { player: { 英雄血: 0, 场上: [] }, enemy: { 英雄血: 0, 场上: [] } },
      手牌: []
    };
  }

  function 深(x) { return JSON.parse(JSON.stringify(x)); }
  function 稳(x) { return JSON.stringify(x); }

  /* 求差：把"上一次的权威"与"这一次采到的"比出**最小变更集**（供事件层记录/回放）。
     单位按 id 认：`场上` 里放的是 id，单位的字段在 `单位` 映射里比。 */
  function 求差(旧, 新) {
    var 变更 = [], 事件 = [];
    function 记(类型, 路径, 值, 前值) { 变更.push({ 类型: 类型, 路径: 路径, 值: 值, 前值: 前值 }); }
    if (!旧) { 记('置', ['整局'], 深(新), null); 事件.push({ 类型: '开局', revision: 新.revision }); return { 变更: 变更, 事件: 事件 }; }

    ['回合', '法力', '法力上限', '手牌'].forEach(function (键) {
      if (稳(旧[键]) === 稳(新[键])) return;
      记('置', [键], 深(新[键]), 深(旧[键]));
      事件.push({ 类型: 键 + '变化', 前: 旧[键], 后: 新[键] });
    });

    var 旧单位 = 旧.单位 || {}, 新单位 = 新.单位 || {};
    ['player', 'enemy'].forEach(function (席) {
      var a = 旧.席位[席], b = 新.席位[席];
      if (!a || !b) return;
      if (a.英雄血 !== b.英雄血) {
        记('置', ['席位', 席, '英雄血'], b.英雄血, a.英雄血);
        事件.push({ 类型: '英雄血量变化', 席位: 席, 前: a.英雄血, 后: b.英雄血 });
      }
      var 旧场上 = a.场上 || [], 新场上 = b.场上 || [];
      /* ⓪ 只有**顺序**变了（id 集合一样）：压入/抽出都表达不了它 ——
         重放只能得到旧顺序，原子性检查就会当成"不自洽"（实测报过一次）。
         所以这种情形直接**整置这一排**：变更集大一点，但重放得出的结果是对的。 */
      var 集合相同 = 旧场上.length === 新场上.length &&
                    旧场上.every(function (id) { return 新场上.indexOf(id) >= 0; });
      if (集合相同 && 稳(旧场上) !== 稳(新场上)) {
        记('置', ['席位', 席, '场上'], 深(新场上), 深(旧场上));
        事件.push({ 类型: '场上重排', 席位: 席, 前: 旧场上, 后: 新场上 });
      } else {
        /* ① 上场：压入 id **+ 把它的字段置进 单位 映射**。
           ⚠ 只压 id 是不够的（第一版就漏了这句，靠"差异路径"当场读出来）：
             新单位的攻/血/攻耗/恢复在 `单位` 里，不写进去，重放出来就是一只空壳。 */
        新场上.forEach(function (id) {
          if (旧场上.indexOf(id) < 0) {
            记('压入', ['席位', 席, '场上'], id);
            if (新单位[id]) 记('置', ['单位', id], 深(新单位[id]), null);
            事件.push({ 类型: '上场', 席位: 席, 单位: id, 卡: (新单位[id] || {}).卡 });
          }
        });
        /* ② 场上单位的字段变化（攻/血/攻耗/恢复）：置到 单位 映射上 */
        新场上.forEach(function (id) {
          if (旧场上.indexOf(id) < 0) return;
          var u = 新单位[id], o = 旧单位[id];
          if (!u) return;
          if (!o || 稳(o) !== 稳(u)) {
            记('置', ['单位', id], 深(u), o ? 深(o) : null);
            事件.push({ 类型: '单位变化', 席位: 席, 单位: id, 前: o || null, 后: u });
          }
        });
        /* ③ 下场：抽出 id，并**删掉 单位 映射里那份** —— 少删这一下，重放出来的旧状态里
           会留着那只已经死掉的随从，原子性检查又会误判（第一版就漏了这句）。 */
        旧场上.forEach(function (id) {
          if (新场上.indexOf(id) < 0) {
            记('抽出', ['席位', 席, '场上'], id);
            记('删', ['单位', id], null, 深(旧单位[id]));
            事件.push({ 类型: '下场', 席位: 席, 单位: id, 卡: (旧单位[id] || {}).卡 });
          }
        });
      }
    });
    return { 变更: 变更, 事件: 事件 };
  }

  /* 把变更应用到一份状态上（回放/重放用）。
     路径中间不存在时会**顺手建出来** —— 例如 `置 ['单位', id]` 时旧状态还没有 `单位` 这个键：
     宁可在重放里补一个空壳，也不要抛 TypeError（那种错会让原子性检查整条失效）。 */
  function 应用(状态, 变更) {
    var 新 = 深(状态);
    变更.forEach(function (c) {
      if (c.类型 === '置' && c.路径.length === 1 && c.路径[0] === '整局') { 新 = 深(c.值); return; }
      if (c.类型 === '置') {
        var p = 新;
        for (var i = 0; i < c.路径.length - 1; i++) {
          if (p[c.路径[i]] === undefined || p[c.路径[i]] === null) p[c.路径[i]] = {};
          p = p[c.路径[i]];
        }
        p[c.路径[c.路径.length - 1]] = 深(c.值);
        return;
      }
      if (c.类型 === '删') {
        var d = 新;
        for (var m = 0; m < c.路径.length - 1; m++) {
          if (d[c.路径[m]] === undefined) return;
          d = d[c.路径[m]];
        }
        delete d[c.路径[c.路径.length - 1]];
        return;
      }
      if (c.类型 === '压入' || c.类型 === '抽出') {
        var q = 新;
        for (var j = 0; j < c.路径.length - 1; j++) {
          if (q[c.路径[j]] === undefined) q[c.路径[j]] = [];
          q = q[c.路径[j]];
        }
        var 末 = q[c.路径[c.路径.length - 1]];
        if (!(末 instanceof Array)) return;
        if (c.类型 === '压入') 末.push(c.值);
        else { var k = 末.indexOf(c.值); if (k >= 0) 末.splice(k, 1); }
      }
    });
    return 新;
  }

  /* 两份状态**差在哪**（逐路径找，最多 8 条）—— 给 ATOMIC_VIOLATION 当证据。
     为什么必须带上这个：第一版报错只给了 `{原因, revision}`，看到"提交不自洽"却
     完全不知道是哪个字段对不上，等于没报。 */
  function 差异路径(a, b, 前缀, 出) {
    出 = 出 || [];
    if (出.length >= 8) return 出;
    if (稳(a) === 稳(b)) return 出;
    var 是对象 = function (x) { return x && typeof x === 'object'; };
    if (!是对象(a) || !是对象(b)) { 出.push({ 路径: 前缀, 重放: a, 采到: b }); return 出; }
    var 键 = {};
    Object.keys(a).forEach(function (k) { 键[k] = 1; });
    Object.keys(b).forEach(function (k) { 键[k] = 1; });
    Object.keys(键).forEach(function (k) {
      差异路径(a[k], b[k], 前缀 ? 前缀 + '.' + k : k, 出);
    });
    return 出;
  }

  /* ---------------------------------------------------------------- 对外 */
  var 权威 = null;
  var 日志 = [];

  /* 提交点：采一次 → 求差 → revision + 1 → 应用 → 记事件。
     返回 { revision, 变更, 事件, 问题[] }；`问题` 就是检错层要的三条：
       ATOMIC_VIOLATION / REVISION_GAP / LOG_INCOMPLETE。
     ★ 每条问题都是 `{ 码, 上下文 }`（2026-10-04 改）：上下文里带**差异路径**，
       这样报告里能直接看到"是哪一条路径对不上、重放成了什么、采到的是什么"。 */
  function 提交(取, 原因) {
    var 问题 = [];
    var 新 = 取 ? 取() : null;
    if (!新) return { revision: 权威 ? 权威.revision : 0, 变更: [], 事件: [],
                      问题: [{ 码: 'META_INCOMPLETE', 上下文: { 原因: '采集不到状态', 提交原因: 原因 || '' } }] };
    var 旧 = 权威;
    var 差 = 求差(旧, 新);
    新.revision = (旧 ? 旧.revision : 0) + 1;
    新.展示revision = 旧 ? 旧.展示revision : 0;

    /* ① 原子性：把变更应用回旧状态，必须**逐字段等于**新状态（否则"施工图"与"成品"不符） */
    if (旧) {
      var 重放 = 应用(旧, 差.变更);
      var a = 深(重放), b = 深(新);
      a.revision = b.revision; a.展示revision = b.展示revision;      // 版本号不是"变更"的产物
      if (稳(a) !== 稳(b)) {
        问题.push({ 码: 'ATOMIC_VIOLATION',
                    上下文: { 原因: 原因 || '', revision: 新.revision, 差异: 差异路径(a, b, '', []) } });
      }
    }
    /* ② revision 必须连续（跳号 = 有人绕过了这个入口） */
    if (旧 && 新.revision !== 旧.revision + 1) {
      问题.push({ 码: 'REVISION_GAP', 上下文: { 旧: 旧.revision, 新: 新.revision } });
    }
    /* ③ 每次提交都要有事件可记（否则日志不全、不可回放） */
    if (旧 && 差.变更.length > 0 && 差.事件.length === 0) {
      问题.push({ 码: 'LOG_INCOMPLETE', 上下文: { 原因: 原因 || '', 变更数: 差.变更.length } });
    }

    权威 = 新;
    日志.push({ revision: 新.revision, 原因: 原因 || '', 变更: 差.变更, 事件: 差.事件 });
    if (日志.length > 300) 日志.shift();
    return { revision: 新.revision, 变更: 差.变更, 事件: 差.事件, 问题: 问题 };
  }

  /* 对账：**非提交点**的任何 DOM 变化都在这里现形（"两套真相"的探针）。
     返回差异列表；调用方（界面/检错层）负责上报与追平。 */
  function 对账(取) {
    if (!权威) return [];
    var 现 = 取 ? 取() : null;
    if (!现) return [{ 项: '整局', 说明: '采不到当前场面' }];
    var 差 = [];
    ['回合', '法力', '法力上限', '手牌'].forEach(function (键) {
      if (稳(权威[键]) !== 稳(现[键])) 差.push({ 项: 键, 权威: 权威[键], 现: 现[键] });
    });
    ['player', 'enemy'].forEach(function (席) {
      if (权威.席位[席].英雄血 !== 现.席位[席].英雄血) {
        差.push({ 项: 席 + '.英雄血', 权威: 权威.席位[席].英雄血, 现: 现.席位[席].英雄血 });
      }
      if (稳(权威.席位[席].场上) !== 稳(现.席位[席].场上)) {
        差.push({ 项: 席 + '.场上', 权威: 权威.席位[席].场上, 现: 现.席位[席].场上 });
      }
      /* 场上**每一只**的具体数值也要对。为什么必须单列一条：
         `场上` 现在只放 id（形状对齐引擎），"某只随从的血被谁从 4 改成 1"这种事
         不会改变 id 序列 —— 只比场上数组就漏掉了，而那正是最典型的"两套真相"。 */
      (权威.席位[席].场上 || []).forEach(function (id) {
        var a = (权威.单位 || {})[id], b = (现.单位 || {})[id];
        if (!b) { 差.push({ 项: id, 说明: '权威里在场、界面采不到它', 权威: a, 现: null }); return; }
        if (a && 稳(a) !== 稳(b)) 差.push({ 项: id + '.数值', 权威: a, 现: b });
      });
    });
    return 差;
  }

  /* 追平展示：按权威把关键数字重画回去（"跳过动画"就调它）。
     传进来的 `画` 由界面提供（怎么写数字是界面的事）。 */
  function 追平(画) {
    if (!权威) return false;
    if (typeof 画 !== 'function') return false;
    try { 画(深(权威)); 权威.展示revision = 权威.revision; return true; }
    catch (e) { return false; }
  }

  /* 标记"展示追到了第几版"（演出播完某段之后由界面调） */
  function 展示追到(rev) {
    if (!权威) return;
    权威.展示revision = Math.min(rev === undefined ? 权威.revision : rev, 权威.revision);
  }

  function 读() { return 权威 ? 深(权威) : null; }
  function 版本号() { return 权威 ? { revision: 权威.revision, 展示revision: 权威.展示revision } : null; }
  function 日志读(n) { return 日志.slice(-(n || 10)); }
  function 重置() { 权威 = null; 日志 = []; }

  W.HS_STATE = {
    版本: 版本,
    空: 空,
    求差: 求差,
    应用: 应用,
    提交: 提交,
    对账: 对账,
    追平: 追平,
    展示追到: 展示追到,
    读: 读,
    版本号: 版本号,
    日志: 日志读,
    重置: 重置
  };
})(typeof window !== 'undefined' ? window : globalThis);
